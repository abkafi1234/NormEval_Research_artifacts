"""Emit the 204-language orthographic compression table as a LaTeX fragment."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Paper", "appendix_cr_table.tex")
A = json.load(open(os.path.join(HERE, "artifacts/tier_a_orthographic.json"), encoding="utf-8"))
per = A["per_language"]

rows = sorted(per.items(), key=lambda kv: (-kv[1]["CR_ortho"]))
n = len(rows)
third = (n + 2) // 3
cols = [rows[0:third], rows[third:2 * third], rows[2 * third:]]
maxlen = max(len(c) for c in cols)

lines = []
lines.append("% Auto-generated by benchmark/make_appendix_table.py -- do not hand-edit.")
lines.append(r"\begin{table}[ht]")
lines.append(r"\centering")
lines.append(r"\tiny")
lines.append(r"\setlength{\tabcolsep}{3pt}")
lines.append(r"\caption{Orthographic compression $CR_{\text{ortho}}$ for all 204 FLORES-200 "
             r"language--script variants, computed on dev+devtest (${\sim}2{,}009$ sentences each). "
             r"$CR_{\text{ortho}}$ isolates the vocabulary reduction obtained from Unicode "
             r"normalization, case folding, diacritic stripping, and punctuation removal alone, "
             r"with no morphological processing. Sorted descending. Values near $1.0$ indicate a "
             r"writing system from which a bundled pipeline harvests almost no vocabulary "
             r"reduction before stemming begins.}")
lines.append(r"\label{tab:appendix_cr_ortho}")
lines.append(r"\begin{tabular}{lr@{\hskip 12pt}lr@{\hskip 12pt}lr}")
lines.append(r"\toprule")
lines.append(r"\textbf{Variant} & $\mathbf{CR_{\text{ortho}}}$ & \textbf{Variant} & "
             r"$\mathbf{CR_{\text{ortho}}}$ & \textbf{Variant} & $\mathbf{CR_{\text{ortho}}}$ \\")
lines.append(r"\midrule")
for i in range(maxlen):
    cells = []
    for c in cols:
        if i < len(c):
            code, d = c[i]
            cells.append(f"{code.replace('_', chr(92)+'_')} & {d['CR_ortho']:.4f}")
        else:
            cells.append(" & ")
    lines.append(" & ".join(cells) + r" \\")
lines.append(r"\bottomrule")
lines.append(r"\end{tabular}")
lines.append(r"\end{table}")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {os.path.abspath(OUT)}  ({maxlen} body rows x 3 columns, {n} variants)")

by = A["by_script"]
print("\n--- by-script summary rows ---")
for s, v in list(by.items()):
    if v["n_languages"] >= 2:
        print(f"{s} & {v['n_languages']} & {v['mean_CR_ortho']:.4f} & "
              f"{v['min']:.4f} & {v['max']:.4f} \\\\")
